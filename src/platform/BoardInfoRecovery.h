// Данные платы из OTP QSPI-flash, если ядро не прочитало их при запуске (KI-032).
//
// Вариант OPTA ядра читает данные платы (VID/PID USB, MAC, функции) из OTP микросхемы
// QSPI до setup() отдельным mbed::QSPI. Сброс микроконтроллера не сбрасывает микросхему:
// если она в этот момент доделывает стирание или запись, чтение не удается, плата видна
// по USB как VID 0xFFFF, а ядро повторяет чтение при каждом запросе VID/PID/MAC — новым
// mbed::QSPI, который при удалении отключает периферию QSPI под драйвером
// QSPIFBlockDevice: дальше не работают запись раздела OTA и TLS (сертификаты на QSPI).
//
// recoverBoardInfo() — первым делом в setup(): если данные не прочитаны, ждет, пока
// микросхема доделает операцию, и перезагружает устройство — следующий запуск читает
// OTP как обычно. Сама к QSPI не обращается (повторное чтение из setup() параллельно
// с USB ядра закончилось фатальной ошибкой, 2026-10-26). Второй раз подряд перезагрузка
// не делается (флаг в регистре RTC backup), так что зациклиться устройство не может.
#pragma once

enum class BoardInfoRecovery {
    NotNeeded,      // ядро прочитало данные при запуске
    AfterReboot,    // прошлый запуск не прочитал данные и перезагрузил устройство
    Failed          // не прочитаны и после перезагрузки: VID 0xFFFF, QSPI может сбоить
};

// Вызывается до Serial.begin(). Если данные не прочитаны и прошлый запуск не
// перезагружал устройство ради них, ждет 1,5 с, перезагружает и не возвращается.
